-- lgen/exporter.lua
-- Converts Markdown colorschemes to configuration formats for popular terminal emulators
-- Supports: Alacritty, Kitty, Ghostty, WezTerm, Neovim, Foot, Xresources, Windows Terminal

local cm = require("lgen.color_math")

local M = {}

local function to_hex(val, fallback)
  if not val then return fallback or "#000000" end
  if type(val) == "string" then
    local rgb = cm.hex_to_rgb(val)
    return rgb and rgb.hex or val
  elseif type(val) == "table" then
    return val.hex or cm.rgb_to_hex(val)
  end
  return fallback or "#000000"
end

local function clean_hex(hex)
  return hex:gsub("^#", "")
end

function M.export(palette, format_name, meta)
  meta = meta or {}
  format_name = (format_name or "kitty"):lower()
  local name = meta.name or "Exported Theme"

  local bg  = to_hex(palette.bg or palette[0], "#000000")
  local fg  = to_hex(palette.fg or palette[7], "#ffffff")
  local cur = to_hex(palette.cursor, fg)
  local sel = to_hex(palette.selection, to_hex(palette[0], "#222222"))

  local c = {}
  for i = 0, 15 do
    c[i] = to_hex(palette[i], i < 8 and "#555555" or "#aaaaaa")
  end

  local lines = {}
  local function out(fmt, ...)
    table.insert(lines, string.format(fmt, ...))
  end

  if format_name == "kitty" then
    out("# Theme: %s", name)
    out("# Generated by lgen (ANSI Colorscheme Auditor)")
    out("")
    out("background %s", bg)
    out("foreground %s", fg)
    out("cursor %s", cur)
    out("selection_background %s", sel)
    out("")
    for i = 0, 15 do
      out("color%d %s", i, c[i])
    end

  elseif format_name == "alacritty" or format_name == "toml" then
    out("# Theme: %s", name)
    out("# Generated by lgen")
    out("")
    out("[colors.primary]")
    out("background = \"%s\"", bg)
    out("foreground = \"%s\"", fg)
    out("")
    out("[colors.cursor]")
    out("cursor = \"%s\"", cur)
    out("text = \"%s\"", bg)
    out("")
    out("[colors.selection]")
    out("background = \"%s\"", sel)
    out("text = \"%s\"", fg)
    out("")
    out("[colors.normal]")
    out("black   = \"%s\"", c[0])
    out("red     = \"%s\"", c[1])
    out("green   = \"%s\"", c[2])
    out("yellow  = \"%s\"", c[3])
    out("blue    = \"%s\"", c[4])
    out("magenta = \"%s\"", c[5])
    out("cyan    = \"%s\"", c[6])
    out("white   = \"%s\"", c[7])
    out("")
    out("[colors.bright]")
    out("black   = \"%s\"", c[8])
    out("red     = \"%s\"", c[9])
    out("green   = \"%s\"", c[10])
    out("yellow  = \"%s\"", c[11])
    out("blue    = \"%s\"", c[12])
    out("magenta = \"%s\"", c[13])
    out("cyan    = \"%s\"", c[14])
    out("white   = \"%s\"", c[15])

  elseif format_name == "ghostty" then
    out("# Theme: %s", name)
    out("# Generated by lgen")
    out("")
    out("background = %s", bg)
    out("foreground = %s", fg)
    out("cursor-color = %s", cur)
    out("selection-background = %s", sel)
    out("")
    for i = 0, 15 do
      out("palette = %d=%s", i, c[i])
    end

  elseif format_name == "wezterm" then
    out("-- Theme: %s", name)
    out("-- Generated by lgen")
    out("return {")
    out("  colors = {")
    out("    background = \"%s\",", bg)
    out("    foreground = \"%s\",", fg)
    out("    cursor_bg = \"%s\",", cur)
    out("    cursor_fg = \"%s\",", bg)
    out("    selection_bg = \"%s\",", sel)
    out("    selection_fg = \"%s\",", fg)
    out("    ansi = {")
    out("      \"%s\", \"%s\", \"%s\", \"%s\",", c[0], c[1], c[2], c[3])
    out("      \"%s\", \"%s\", \"%s\", \"%s\",", c[4], c[5], c[6], c[7])
    out("    },")
    out("    brights = {")
    out("      \"%s\", \"%s\", \"%s\", \"%s\",", c[8], c[9], c[10], c[11])
    out("      \"%s\", \"%s\", \"%s\", \"%s\",", c[12], c[13], c[14], c[15])
    out("    },")
    out("  },")
    out("}")

  elseif format_name == "nvim" or format_name == "lua" then
    out("-- Theme: %s", name)
    out("-- Generated by lgen")
    out("return {")
    out("  name = %q,", name)
    out("  bg = %q,", bg)
    out("  fg = %q,", fg)
    out("  cursor = %q,", cur)
    out("  selection = %q,", sel)
    out("  black = %q,", c[0])
    out("  red = %q,", c[1])
    out("  green = %q,", c[2])
    out("  yellow = %q,", c[3])
    out("  blue = %q,", c[4])
    out("  magenta = %q,", c[5])
    out("  cyan = %q,", c[6])
    out("  white = %q,", c[7])
    out("  bright_black = %q,", c[8])
    out("  bright_red = %q,", c[9])
    out("  bright_green = %q,", c[10])
    out("  bright_yellow = %q,", c[11])
    out("  bright_blue = %q,", c[12])
    out("  bright_magenta = %q,", c[13])
    out("  bright_cyan = %q,", c[14])
    out("  bright_white = %q,", c[15])
    out("}")

  elseif format_name == "foot" then
    out("# Theme: %s", name)
    out("# Generated by lgen")
    out("")
    out("[colors]")
    out("background=%s", clean_hex(bg))
    out("foreground=%s", clean_hex(fg))
    out("regular0=%s", clean_hex(c[0]))
    out("regular1=%s", clean_hex(c[1]))
    out("regular2=%s", clean_hex(c[2]))
    out("regular3=%s", clean_hex(c[3]))
    out("regular4=%s", clean_hex(c[4]))
    out("regular5=%s", clean_hex(c[5]))
    out("regular6=%s", clean_hex(c[6]))
    out("regular7=%s", clean_hex(c[7]))
    out("bright0=%s", clean_hex(c[8]))
    out("bright1=%s", clean_hex(c[9]))
    out("bright2=%s", clean_hex(c[10]))
    out("bright3=%s", clean_hex(c[11]))
    out("bright4=%s", clean_hex(c[12]))
    out("bright5=%s", clean_hex(c[13]))
    out("bright6=%s", clean_hex(c[14]))
    out("bright7=%s", clean_hex(c[15]))

  elseif format_name == "xresources" or format_name == "xterm" then
    out("! Theme: %s", name)
    out("! Generated by lgen")
    out("*.background: %s", bg)
    out("*.foreground: %s", fg)
    out("*.cursorColor: %s", cur)
    for i = 0, 15 do
      out("*.color%d: %s", i, c[i])
    end

  elseif format_name == "windows_terminal" or format_name == "wt" then
    out("{")
    out("  \"name\": %q,", name)
    out("  \"background\": %q,", bg)
    out("  \"foreground\": %q,", fg)
    out("  \"cursorColor\": %q,", cur)
    out("  \"selectionBackground\": %q,", sel)
    out("  \"black\": %q,", c[0])
    out("  \"red\": %q,", c[1])
    out("  \"green\": %q,", c[2])
    out("  \"yellow\": %q,", c[3])
    out("  \"blue\": %q,", c[4])
    out("  \"purple\": %q,", c[5])
    out("  \"cyan\": %q,", c[6])
    out("  \"white\": %q,", c[7])
    out("  \"brightBlack\": %q,", c[8])
    out("  \"brightRed\": %q,", c[9])
    out("  \"brightGreen\": %q,", c[10])
    out("  \"brightYellow\": %q,", c[11])
    out("  \"brightBlue\": %q,", c[12])
    out("  \"brightPurple\": %q,", c[13])
    out("  \"brightCyan\": %q,", c[14])
    out("  \"brightWhite\": %q", c[15])
    out("}")

  else
    return nil, string.format("Unsupported export format: '%s'. Supported: alacritty, kitty, ghostty, wezterm, nvim, foot, xresources, windows_terminal", format_name)
  end

  return table.concat(lines, "\n") .. "\n"
end

return M
